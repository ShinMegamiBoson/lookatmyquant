"""Which tuning each common NVIDIA card gets, from the measured tables in runtime_cuda/inkling/tuning/.

    python runtime_cuda/tuning_coverage.py            # print the table
    python runtime_cuda/tuning_coverage.py --write    # also write runtime_cuda/inkling/tuning/COVERAGE.md

The card list holds spec-sheet values (compute capability, SM count); at run time the runtime reads the real card's
values from the driver, so this list only drives the report. Resolution is `tuning.resolve`: the card's own table,
else the nearest measured card of its architecture, else a cross-architecture guess or rules.
"""
