def info_for(name, cc, sms) -> TU.GpuInfo:
    l1 = TU.L1_PER_SM_KB[cc] * 1024
    return TU.GpuInfo(name, cc, sms, 0, 0, 0, l1, 0.0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    tables = TU._load_tables()
    measured = {e["gpu"]["key"] for e in tables}
    lines = ["# Tuning coverage", "",
             f"Measured tables: {', '.join(sorted(measured)) or 'none'}. Generated by `runtime_cuda/tuning_coverage.py` "
             "from spec-sheet SM counts; the runtime reads the real card at load time.", "",
             "| Card | Arch | SMs | Source | Two-weight tables | Attention split | MoE GEMV (BM, BC, warps, stages) |",
             "|---|---|---:|---|---|---:|---|"]
    for name, cc, sms in CARDS:
        info = info_for(name, cc, sms)
        t = TU.resolve(info, tables)
        src = t.source
        kind = ("**measured**" if src.startswith("measured") else
                "nearest " + src.split("card ")[1].split(" (")[0] if src.startswith("nearest") else
                "cross-arch from " + src.split("from ")[1].split(" (")[0] if src.startswith("cross") else "rules")
        mt = ", ".join(sorted(t.multitable)) or "none"
        lines.append(f"| {name.replace('NVIDIA ', '').replace('GeForce ', '')} | sm{cc[0]}{cc[1]} | {sms} | {kind} | {mt} | "
                     f"{t.attn_nsplit} | {list(t.gemv_cfg('moe'))} |")
    out = "\n".join(lines) + "\n"
    print(out)
    if args.write:
        (TU.TABLE_DIR / "COVERAGE.md").write_text(out)


if __name__ == "__main__":
    main()
